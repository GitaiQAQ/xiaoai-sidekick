"""Generate src/kws_templates.h from `client --kws-dump` output.

Input is the device dump of /tmp/doubao_enroll.wav: per-segment MFCC+delta
features after cepstral mean normalisation. Template choice (tightest
triangle) and the 1.3x cluster threshold are decided by the C scorer, which
reports them as `cluster=a,b,c intra_max=... proposed_threshold=...`.
"""
from pathlib import Path
import sys

DIM = 26


def parse(text):
    cluster, intra, threshold, segs = None, None, None, {}
    frames, seg_id = None, None
    for line in text.splitlines():
        if line.startswith('cluster='):
            body = line.split('cluster=', 1)[1]
            ids, rest = body.split(' ', 1)
            cluster = [int(x) for x in ids.split(',')]
            for token in rest.split():
                if token.startswith('intra_max='):
                    intra = float(token.split('=')[1])
                elif token.startswith('proposed_threshold='):
                    threshold = float(token.split('=')[1])
        elif line.startswith('dump segment='):
            parts = dict(tok.split('=') for tok in line.split()[1:])
            seg_id = int(parts['segment'])
            frames = []
            segs[seg_id] = {'frames': frames, 'declared': int(parts['frames'])}
        elif line.startswith('f ') and seg_id is not None:
            values = [float(x) for x in line[2:].split()]
            if len(values) != DIM:
                raise SystemExit('bad feature row width %d' % len(values))
            frames.append(values)
    if not cluster or intra is None or threshold is None:
        raise SystemExit('missing cluster/threshold line in dump')
    for sid, info in segs.items():
        if len(info['frames']) != info['declared']:
            raise SystemExit('segment %d frame count mismatch' % sid)
    return cluster, intra, threshold, segs


def main():
    if len(sys.argv) < 2:
        raise SystemExit('usage: kws-build-templates.py <dump.txt> [cli-threshold] [segment-ids]')
    dump = Path(sys.argv[1]).read_text(encoding='utf-8-sig')
    cluster, intra, threshold, segs = parse(dump)
    if len(sys.argv) > 3:
        cluster = [int(v) for v in sys.argv[3].split(',')]
    if len(sys.argv) > 2:
        threshold = float(sys.argv[2])
        note = 'cli override'
    else:
        # The C scorer proposes 1.3x for a quiet room. Field tests showed that
        # arbitrary speech lands at 10.6-14.7, so keep the accepted band tight.
        threshold = round(intra * 1.10, 4)
        note = '1.10 x cluster max'
    missing = [c for c in cluster if c not in segs]
    if missing:
        raise SystemExit('cluster segment %r missing from dump' % missing)
    if len(sys.argv)>3:
        import re
        pairs={(int(a),int(b)):float(d) for a,b,d in re.findall(r'dtw\[(\d+)\]\[(\d+)\]=([0-9.]+)',dump)}
        intra=max((pairs[tuple(sorted((a,b)))] for i,a in enumerate(cluster) for b in cluster[i+1:]),default=0.0)
    lengths = [len(segs[c]['frames']) for c in cluster]
    offsets, total = [], 0
    for n in lengths:
        offsets.append(total)
        total += n
    out = ['/* Generated by tools/kws-build-templates.py; do not edit by hand.',
           '   Source: device enrollment dump of /tmp/doubao_enroll.wav.',
           '   cluster segments: %s' % ','.join(str(c) for c in cluster),
           '   threshold = %s = %.4f (cluster max %.4f) */' % (note, threshold, intra),
           '#ifndef LX06_KWS_TEMPLATES_H',
           '#define LX06_KWS_TEMPLATES_H',
           '',
           '#define LX_KWS_TEMPLATE_COUNT %d' % len(cluster),
           '#define LX_KWS_TEMPLATE_INTRA_MAX %.4ff' % intra,
           '',
           'static const unsigned short lx_kws_template_len[%d] = {%s};' %
           (len(cluster), ', '.join(str(n) for n in lengths)),
           'static const unsigned int lx_kws_template_off[%d] = {%s};' %
           (len(cluster), ', '.join(str(o) for o in offsets)),
           'static const float lx_kws_template_threshold = %.4ff;' % threshold,
           'static const float lx_kws_template_intra_max = LX_KWS_TEMPLATE_INTRA_MAX;',
           '',
           'static const float lx_kws_template_feat[%d] = {' % (total * DIM)]
    for sid in cluster:
        out.append('    /* segment %d, %d frames */' % (sid, len(segs[sid]['frames'])))
        for row in segs[sid]['frames']:
            out.append('    ' + ', '.join('%.4ff' % v for v in row) + ',')
    out += ['};', '', '#endif', '']
    path = Path(__file__).resolve().parents[1] / 'src' / 'kws_templates.h'
    path.write_text('\n'.join(out), encoding='utf-8')
    print('wrote %s templates=%d frames=%s threshold=%.4f intra_max=%.4f' %
          (path, len(cluster), lengths, threshold, intra))


main()
